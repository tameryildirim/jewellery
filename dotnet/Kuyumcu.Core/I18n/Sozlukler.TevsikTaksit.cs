    /// <summary>Ham durum kodunu sade ada çevirir (UX-S31: kod ekrana basılmaz).</summary>
    public string Durum(string? kod) => kod switch
    {
        "ACIK" => DurumAcik,
        "BILDIRILDI" => DurumBildirildi,
        "SURE_DOLDU" => DurumSureDoldu,
        "GECERSIZ" => DurumGecersiz,
        _ => kod ?? "",
    };

    /// <summary>Ham tür kodunu sade ada çevirir.</summary>
    public string Tur(string? kod) => kod switch
    {
        "GUNLUK_KUMULATIF" => TurGunluk,
        "ISLEM_TUTARI" => TurIslem,
        "TAKSIT" => TurTaksit,
        _ => kod ?? "",
    };

    /// <summary>Hareket türünü sade ada çevirir (kod ekrana basılmaz).</summary>
    public string Islem(string? tur) => tur switch
    {
        "SATIS" => IslemSatis,
        "ALIS" => IslemAlis,
        "HURDA_ALIS" => IslemHurdaAlis,
        "TAHSILAT" => IslemTahsilat,
        _ => IslemDiger,
    };

    /// <summary>Ham yön kodunu sade ada çevirir.</summary>
    public string Yon(string? kod) => kod == "ODEME" ? YonOdeme : YonTahsilat;
}

