    /// <summary>PAKET RAPOR-2: Panel BASİT kâr satırının KISA eksik metni — "9 satış, 1 iade" (satır içinde bölünmez).</summary>
    public static string EksikSayiKisa(KarRaporMetinleri m, int satis, int iade) =>
        satis > 0 && iade > 0 ? string.Format(m.EksikSatisVeIadeKisa, string.Format(m.EksikSatisSayi, satis), string.Format(m.EksikIadeSayi, iade))
        : EksikSayi(m, satis, iade);

    /// <summary>PAKET RAPOR-3: kâr satırında neyin eksik olduğunu SÖYLEYEN parça — "12 satışın maliyeti yok",
    /// "1 iadenin maliyeti yok", "12 satış ve 1 iadenin maliyeti yok" (tek kural).</summary>
    public static string MaliyetYok(KarRaporMetinleri m, int satis, int iade) =>
        satis > 0 && iade > 0 ? string.Format(m.MaliyetYokIkisi, satis, iade)
        : iade > 0 ? string.Format(m.MaliyetYokIade, iade)
        : string.Format(m.MaliyetYokSatis, satis);

    /// <summary>MADEN-2: maliyeti eksik hareket sayısı metni — "2 satış", "1 iade", "2 satış ve 1 iade" (tek kural).</summary>
    public static string EksikSayi(KarRaporMetinleri m, int satis, int iade) =>
        satis > 0 && iade > 0 ? string.Format(m.EksikSatisVeIade, string.Format(m.EksikSatisSayi, satis), string.Format(m.EksikIadeSayi, iade))
        : iade > 0 ? string.Format(m.EksikIadeSayi, iade)
        : string.Format(m.EksikSatisSayi, satis);
