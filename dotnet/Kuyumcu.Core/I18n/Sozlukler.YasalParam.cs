    public static YasalParamMetinleri Al(string dil) => dil == "en" ? En : Tr;

    /// <summary>
    /// MASAK kimlik kuralının TEK cümlesi (bütün ekranlar): md.5/1-b kimlik eşiği + (daha
    /// düşükse) amaç beyanı kademesi. Sayılar sunucudan; biçim çağıranın Bicim.Tl'sinden.
    /// </summary>
    public static string KimlikKuraliMetni(string dil, decimal kimlikEsigi, decimal amacEsigi, Func<decimal, string> tl)
    {
        var m = Al(dil);
        return amacEsigi > 0m && amacEsigi < kimlikEsigi
            ? string.Format(m.KimlikKurali, tl(kimlikEsigi), tl(amacEsigi))
            : string.Format(m.KimlikKuraliTek, tl(kimlikEsigi));
    }
