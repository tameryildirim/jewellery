    /// <summary>Şablon kolonunun okunur adı + parantez içinde dosyadaki başlık ("Ürün kodu (kod)").</summary>
    public string KolonEtiketi(string kolon)
    {
        var ad = kolon switch
        {
            "kod" => KolUrunKodu,
            "adet" => KolAdet,
            "birimMaliyetTl" => KolBirimMaliyet,
            "ad" => KolMusteriAdi,
            "telefon" => KolTelefon,
            "vergiNo" => KolVergiNo,
            "tlBakiye" => KolTlBakiye,
            "hasGramBakiye" => KolHasBakiye,
            "usdBakiye" => string.Format(KolDovizBakiye, "USD"),
            "eurBakiye" => string.Format(KolDovizBakiye, "EUR"),
            "gbpBakiye" => string.Format(KolDovizBakiye, "GBP"),
            _ => null,
        };
        return ad is null ? kolon : $"{ad} ({kolon})";
    }

    /// <summary>Sunucunun satır hata kodunu ekrandaki ada çevirir; bilinmeyen kod olduğu gibi kalır.</summary>
    public string HataKoduAdi(string? kod) => kod switch
    {
        "CARI_YOK" => HkCariYok,
        "CARI_BELIRSIZ" => HkCariBelirsiz,
        "URUN_YOK" => HkUrunYok,
        "URUN_BELIRSIZ" => HkUrunBelirsiz,
        "SISTEM_CARISI" => HkSistemCarisi,
        "PASIF_HEDEF" => HkPasifHedef,
        "ZATEN_ACILIS" => HkZatenAcilis,
        "YINELENEN_SATIR" => HkYinelenenSatir,
        "STOK_VAR" => HkStokVar,
        "SIFIR_SATIR" => HkSifirSatir,
        "HAS_ONDALIK" => HkHasOndalik,
        "TUTAR_ONDALIK" => HkTutarOndalik,
        "ADET_GECERSIZ" => HkAdetGecersiz,
        "MALIYET_SIFIR" => HkMaliyetSifir,
        "MALIYET_NEGATIF" => HkMaliyetNegatif,
        "TUTAR_ASIRI" => HkTutarAsiri,
        "SAYI_GECERSIZ" => HkSayiGecersiz,
        "SAYI_BELIRSIZ" => HkSayiBelirsiz,
        "ALAN_ZORUNLU" => HkAlanZorunlu,
        _ => kod ?? "",
    };
}

